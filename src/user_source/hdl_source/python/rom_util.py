# -*- coding: utf-8 -*-
"""
ROM 生成公共函数: 输出 BRAM ROM / RAM 模块 (.v) 与初值文件 (.mif)

安路 TD 不认 initial 块初始化的 ROM 数组 (综合为无驱动网表, HDL-5314, 上板读出全 0, 见第十四讲),
因此综合时用 EG_LOGIC_BRAM 原语 + INIT_FILE (.mif, 与官方 HX4S20 13_music 例程相同, 综合日志有
SYN-2541 "Reading BRAM init file"); 仿真 (Icarus, 预定义 __ICARUS__) 仍用数组 + initial 初值.
INIT_FILE 路径相对引用它的 .v 文件所在目录 (官方例程 al_ip/blk_mem_gen_0.v 中写 "../data1.mif"),
.mif 与 .v 放在同一目录, 直接写文件名.

write_rom : 单口 ROM (MODE "SP")
write_ram : 带初值的简单双口 RAM (MODE "PDPW", A 口写 / B 口读, 同官方 lab_ex_2 al_ip/ram.v)
"""
import os


def write_mif(path, data, width, depth, comment):
    data = list(data) + [0] * (depth - len(data))
    hw = (width + 3) // 4
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("-- generated by python/%s, do not edit\n" % comment.split()[0])
        f.write("WIDTH=%d;\nDEPTH=%d;\n\nADDRESS_RADIX=HEX;\nDATA_RADIX=HEX;\n\nCONTENT BEGIN\n" % (width, depth))
        for a, v in enumerate(data):
            f.write("\t%04X  :   %0*X;\n" % (a, hw, v))
        f.write("END;\n")


def _sim_init(rom, width, depth):
    lines = "\n".join("    mem[%d] = %d'h%x;" % (a, width, v) for a, v in enumerate(rom) if v)
    return ("integer i;\ninitial begin\n    for (i = 0; i < %d; i = i + 1) mem[i] = %d'h0;\n%s\nend\n"
            % (depth, width, lines))


def write_rom(out_dir, name, rom, aw, comment, implement="32K", width=8, depth=None):
    depth = depth or (1 << aw)
    assert len(rom) <= depth, (name, len(rom), depth)
    mif = name + ".mif"
    write_mif(os.path.join(out_dir, mif), rom, width, depth, comment)
    w1 = width - 1
    with open(os.path.join(out_dir, name + ".v"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// 自动生成, 请勿手改: python/%s\n" % comment)
        f.write("// %d x %d bit ROM, 1 拍同步读 (%d 项有效). 综合: EG_LOGIC_BRAM + %s (BRAM%s);\n"
                % (depth, width, len(rom), mif, implement))
        f.write("// 仿真: 数组 + initial. 不能只用 initial 数组综合 (TD HDL-5314, 上板全 0)\n")
        f.write("module %s(\n    input             clk,\n    input      [%d:0] addr,\n"
                "    output     [%d:0]  q\n);\n" % (name, aw - 1, w1))
        f.write("`ifdef __ICARUS__\nreg [%d:0] mem [0:%d];\nreg [%d:0] q_r;\n" % (w1, depth - 1, w1))
        f.write(_sim_init(rom, width, depth))
        f.write("always @(posedge clk) q_r <= mem[addr];\nassign q = q_r;\n`else\n")
        f.write('''EG_LOGIC_BRAM #(
    .DATA_WIDTH_A (%d),
    .ADDR_WIDTH_A (%d),
    .DATA_DEPTH_A (%d),
    .DATA_WIDTH_B (%d),
    .ADDR_WIDTH_B (%d),
    .DATA_DEPTH_B (%d),
    .MODE         ("SP"),
    .REGMODE_A    ("NOREG"),
    .IMPLEMENT    ("%s"),
    .DEBUGGABLE   ("NO"),
    .PACKABLE     ("NO"),
    .INIT_FILE    ("%s"),
    .FILL_ALL     ("NONE")
) u_bram (
    .dia   ({%d{1'b0}}),
    .dib   ({%d{1'b0}}),
    .addra (addr),
    .addrb ({%d{1'b0}}),
    .cea   (1'b1),
    .ceb   (1'b0),
    .ocea  (1'b0),
    .oceb  (1'b0),
    .clka  (clk),
    .clkb  (1'b0),
    .wea   (1'b0),
    .web   (1'b0),
    .bea   (1'b0),
    .beb   (1'b0),
    .rsta  (1'b0),
    .rstb  (1'b0),
    .doa   (q),
    .dob   ()
);
`endif
endmodule
''' % (width, aw, depth, width, aw, depth, implement, mif, width, width, aw))


def write_ram(out_dir, name, init, aw, width, depth, comment, implement="9K"):
    """简单双口 RAM: A 口写 (we/waddr/wdata), B 口读 (raddr/q, 1 拍), 同一时钟, 上电初值 = init"""
    assert len(init) <= depth, (name, len(init), depth)
    mif = name + ".mif"
    write_mif(os.path.join(out_dir, mif), init, width, depth, comment)
    w1 = width - 1
    with open(os.path.join(out_dir, name + ".v"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// 自动生成, 请勿手改: python/%s\n" % comment)
        f.write("// %d x %d bit 简单双口 RAM (A 写 / B 读, 1 拍同步读), 上电初值 %s. 综合: EG_LOGIC_BRAM PDPW (BRAM%s)\n"
                % (depth, width, mif, implement))
        f.write("module %s(\n    input             clk,\n    input             we,\n"
                "    input      [%d:0] waddr,\n    input      [%d:0]  wdata,\n"
                "    input      [%d:0] raddr,\n    output     [%d:0]  q\n);\n" % (name, aw - 1, w1, aw - 1, w1))
        f.write("`ifdef __ICARUS__\nreg [%d:0] mem [0:%d];\nreg [%d:0] q_r;\n" % (w1, depth - 1, w1))
        f.write(_sim_init(init, width, depth))
        f.write("always @(posedge clk) begin\n    if (we) mem[waddr] <= wdata;\n    q_r <= mem[raddr];\nend\n"
                "assign q = q_r;\n`else\n")
        f.write('''EG_LOGIC_BRAM #(
    .DATA_WIDTH_A (%d),
    .ADDR_WIDTH_A (%d),
    .DATA_DEPTH_A (%d),
    .DATA_WIDTH_B (%d),
    .ADDR_WIDTH_B (%d),
    .DATA_DEPTH_B (%d),
    .MODE         ("PDPW"),
    .REGMODE_A    ("NOREG"),
    .REGMODE_B    ("NOREG"),
    .WRITEMODE_A  ("NORMAL"),
    .WRITEMODE_B  ("NORMAL"),
    .RESETMODE    ("SYNC"),
    .IMPLEMENT    ("%s"),
    .DEBUGGABLE   ("NO"),
    .PACKABLE     ("NO"),
    .INIT_FILE    ("%s"),
    .FILL_ALL     ("NONE")
) u_bram (
    .dia   (wdata),
    .dib   ({%d{1'b0}}),
    .addra (waddr),
    .addrb (raddr),
    .cea   (we),
    .ceb   (1'b1),
    .ocea  (1'b0),
    .oceb  (1'b0),
    .clka  (clk),
    .clkb  (clk),
    .wea   (we),
    .web   (1'b0),
    .bea   (1'b0),
    .beb   (1'b0),
    .rsta  (1'b0),
    .rstb  (1'b0),
    .doa   (),
    .dob   (q)
);
`endif
endmodule
''' % (width, aw, depth, width, aw, depth, implement, mif, width))
